"""Authoring script for the round screen adapter board (KiCad is the single source of truth for this board).
Run with the system python that has pcbnew:  /usr/bin/python3 make_board.py
Writes screen-adapter.kicad_sch (+ knob.kicad_sym, sym-lib-table) / .kicad_pcb / .kicad_pro / fp-lib-table from ONE netlist (COMPS below),
then exports ../screen-adapter.step with kicad-cli. Schematic + board share symbol paths, so DRC schematic parity holds.
Contents: round Edge.Cuts outline, 2 layers, 1.0 thick [A]; footprints from the shared library (electronics/kicad/footprints.pretty):
  J1 = FPC_14P_0.5mm_Top   for the 0.71" round TFT tail (14 pin, 0.5 pitch [A], Zhunyi Z07101-P14); tail pin-out NOT yet wired (NC flags)
  U1 = QFN-20_3x3_P0.4_CH32V003   CH32V003F4U6 [A]: VSS pin 4, VDD pin 6 [CH32V003 DS]; other pins NC until the display link is drawn
  C1 = TubeRodClamp_Adapter_M1.6   v0.2 (2026-10-31): NPTH Ø1.8 for the M1.6 rod; B.Cu ring GND on the tube top, F.Cu ring VBUS_DATA
       under the thin nut (data over power; replaces W1, the 4 wire pads)
  C2 = 100 nF 0402 at U1 VDD/VSS (v0.4: moved from the old U3 position)
  v0.4 (2026-11-01, knob v0.16b [Ed]): U3 TMAG5273 + R1/R2 I2C pull-ups and the SDA/SCL/HALL_INT nets REMOVED (the dial angle sensor
       is dropped, rel_sensor=False; the only TMAG5273 is the 3D Hall in the main-PCB Hall row).
Placed only, no routing (ratsnest left for the layout: the display tail / VBUS_DATA regulator are still open). Grid origin = board centre
(x right, y down in KiCad). Keep electronics/params.py adapter_fps in step (frame coords: y up = -KiCad y)."""
import os, sys, json, subprocess, pcbnew
sys.path.insert(0, os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")))
import sch_gen

PCB_VERSION = "v0.4"
ORIGIN = (100.0, 100.0)     # KiCad position of the board centre (sheet placement only)
BOARD_D = 15.5              # [A] <= 18 (Ed); smallest round that holds J1 with 0.3 courtyard-to-edge
BOARD_T = 1.0               # [A]
J1_POS = (0.0, -3.7)        # [A] KiCad coords (y up = negative); v0.2: 0.5 out for the M1.6 nut at the centre (was -3.2)
U1_POS = (0.0, 3.8)         # [A] v0.2: was 3.5
C1_POS = (0.0, 0.0)         # centre: tube / rod clamp (v0.2 replaces the W1 wire pads)
C2_POS, C2_ROT = (-2.55, 5.2), 90.0   # [A] v0.4: 100 nF next to U1 VSS (4) / VDD (6)
EDGE_CLEAR_CU = 0.3         # [A] copper to board edge (default 0.5 relaxed for the small board)

HERE = os.path.dirname(os.path.abspath(__file__))
NAME = "screen-adapter"
LIBDIR = os.path.normpath(os.path.join(HERE, "..", "..", "footprints.pretty"))
mm = pcbnew.FromMM
def P(x, y): return pcbnew.VECTOR2I(mm(ORIGIN[0] + x), mm(ORIGIN[1] + y))

U1_NETS = {"4": "GND", "6": "VCC"}
COMPS = [
    dict(ref="J1", sym="FPC_14P", value="Z07101-P14 (FPC 14P 0.5)", fp="FPC_14P_0.5mm_Top", pos=J1_POS, rot=0,
         pins=[(str(i + 1), f"P{i + 1}", "passive", "L" if i < 7 else "R") for i in range(14)], nets={str(i + 1): None for i in range(14)},
         fields={"MPN": "Z07101-P14", "Manufacturer": "Zhunyi", "LCSC": "", "Note": "display tail pin-out not wired yet [A]"}),
    dict(ref="U1", sym="CH32V003F4U6", value="CH32V003F4U6", fp="QFN-20_3x3_P0.4_CH32V003", pos=U1_POS, rot=0,
         pins=[(str(i + 1), {"4": "VSS", "6": "VDD"}.get(str(i + 1), f"P{i + 1}"), "power_in" if str(i + 1) in U1_NETS else "passive", "L" if i < 10 else "R") for i in range(20)],
         nets={str(i + 1): U1_NETS.get(str(i + 1)) for i in range(20)}, fields={"MPN": "CH32V003F4U6", "Manufacturer": "WCH", "LCSC": "C5299908"}),
    dict(ref="C1", sym="TubeRodClamp", value="TubeRodClamp_Adapter_M1.6", fp="TubeRodClamp_Adapter_M1.6", pos=C1_POS, rot=0,
         pins=[("1", "TUBE_GND", "passive", "L"), ("2", "NUT_VBUS", "passive", "R")], nets={"1": "GND", "2": "VBUS_DATA"}, fields={}, bom=False),
    dict(ref="C2", sym="C", value="100n", fp="C_0402", pos=C2_POS, rot=C2_ROT, pins=[("1", "~", "passive", "L"), ("2", "~", "passive", "R")],
         nets={"1": "VCC", "2": "GND"}, fields={"MPN": "CL05B104KO5NNNC", "Manufacturer": "Samsung", "LCSC": "C1525"}),
]
for c in COMPS: c.setdefault("bom", True); c["footprint"] = "footprints:" + c["fp"]; c["place"] = c["pos"]; c["side"] = "F"
FLAGS = [dict(ref=f"#FLG0{i + 1}", sym="PWR_FLAG", pins=[("1", "~", "power_out", "L")], value="PWR_FLAG", footprint="", nets={"1": n}, fields={},
              bom=False, place=None, side=None) for i, n in enumerate(("VCC", "GND"))]

def build():
    sch_gen.write(os.path.join(HERE, NAME + ".kicad_sch"), f"Screen adapter {PCB_VERSION}", NAME, COMPS + FLAGS, rev=PCB_VERSION,
                  comment="knob CAD v0.16b; generated by make_board.py (U3 TMAG5273 removed)")
    board = pcbnew.BOARD()
    ds = board.GetDesignSettings(); ds.SetBoardThickness(mm(BOARD_T)); ds.SetCopperLayerCount(2)
    ds.m_CopperEdgeClearance = mm(EDGE_CLEAR_CU)
    c = pcbnew.PCB_SHAPE(board, pcbnew.SHAPE_T_CIRCLE); c.SetLayer(pcbnew.Edge_Cuts); c.SetWidth(mm(0.05))
    c.SetCenter(P(0, 0)); c.SetEnd(P(BOARD_D / 2, 0)); board.Add(c)
    nets = {}
    def net(n):
        if n not in nets: nets[n] = pcbnew.NETINFO_ITEM(board, n); board.Add(nets[n])
        return nets[n]
    for cp in COMPS:
        fp = pcbnew.FootprintLoad(LIBDIR, cp["fp"]); fp.SetFPID(pcbnew.LIB_ID("footprints", cp["fp"]))
        fp.SetReference(cp["ref"]); fp.SetValue(cp["value"]); fp.SetPosition(P(*cp["pos"])); board.Add(fp)
        if cp["rot"]: fp.SetOrientationDegrees(cp["rot"])
        fp.SetPath(pcbnew.KIID_PATH(sch_gen.fp_path(NAME, cp["ref"]))); fp.SetSheetname("Root"); fp.SetSheetfile(NAME + ".kicad_sch")
        for k, v in cp["fields"].items():
            if v: fp.SetField(k, v)
        for t in fp.GetFields():
            if not (t.IsReference() or t.IsValue()): t.SetVisible(False)
        if not cp["bom"]: fp.SetExcludedFromBOM(True); fp.SetExcludedFromPosFiles(True)
        pname = {pn: nm for pn, nm, *_ in cp["pins"]}
        for pad in fp.Pads():
            num = pad.GetNumber()
            if num not in pname: continue
            n = cp["nets"].get(num)
            pad.SetNet(net(n if n else f"unconnected-({cp['ref']}-{pname[num]}-Pad{num})"))
    ds.SetAuxOrigin(P(0, 0)); ds.SetGridOrigin(P(0, 0))
    return board

if __name__ == "__main__":
    board = build()
    pcb_path = os.path.join(HERE, NAME + ".kicad_pcb")
    pcbnew.SaveBoard(pcb_path, board)
    json.dump({"meta": {"filename": NAME + ".kicad_pro", "version": 1},
               "board": {"design_settings": {"rules": {"min_copper_edge_clearance": EDGE_CLEAR_CU}}},
               "sheets": [[sch_gen.uid(NAME, "root"), "Root"]], "libraries": {}},
              open(os.path.join(HERE, NAME + ".kicad_pro"), "w"), indent=2)
    open(os.path.join(HERE, "fp-lib-table"), "w").write(
        '(fp_lib_table\n  (version 7)\n  (lib (name "footprints")(type "KiCad")(uri "${KIPRJMOD}/../../footprints.pretty")(options "")(descr "Ed project footprints"))\n)\n')
    step = os.path.join(HERE, "..", NAME + ".step")
    subprocess.run(["kicad-cli", "pcb", "export", "step", "--grid-origin", "--force", "-o", step, pcb_path], check=True, capture_output=True)
    print("board Ø", BOARD_D, *[(c["ref"], c["pos"], c["rot"]) for c in COMPS])
