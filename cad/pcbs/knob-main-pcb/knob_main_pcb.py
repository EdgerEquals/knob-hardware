"""Reader + drawer for the knob main PCB. The board itself is authored in KiCad (single source of truth):
  kicad/knob-main-pcb.kicad_pcb  (generated by kicad/make_board.py)  ->  knob-main-pcb.step (kicad-cli export)
This module holds NO board geometry. It reads the KiCad file for the facts other parts need
(board thickness, motor footprint position) and imports the KiCad STEP.
World axes (tools/sheet.py): X = panel x, Y = -(panel y from top), Z = -(depth behind panel front).
STEP from kicad-cli --grid-origin: grid origin = panel top-left, so STEP X/Y already equal world X/Y; Z = 0 at the board back."""
import os, re, sys
from build123d import import_step, Pos
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(HERE)), "tools"))
KICAD_PCB = os.path.join(HERE, "kicad", "knob-main-pcb.kicad_pcb")
STEP = os.path.join(HERE, "knob-main-pcb.step")
Z_PCB_FRONT = 20.2     # [L] depth of the board front (F) face behind the panel front, layout v5 depth stack

def kicad_facts(path=KICAD_PCB):
    t = open(path).read()
    thick = float(re.search(r"\(general\s*\(thickness ([\d.]+)\)", t).group(1))
    gx, gy = map(float, re.search(r"\(grid_origin ([\d.\-]+) ([\d.\-]+)\)", t).group(1, 2))
    def at(fpname):
        m = re.search(r'\(footprint "footprints:' + fpname + r'".*?\(at ([\d.\-]+) ([\d.\-]+)', t, re.S)
        return (float(m.group(1)) - gx, float(m.group(2)) - gy) if m else (None, None)
    mx, my = at(re.escape("Motor_1220_Tabs"))
    sx, sy = at(r"(?:Shaft_Hole_NPTH_[\d.]+mm|TubeRodClamp_Main_[^\"]+)")   # any H1 hole size
    def drill(fpname):
        b = re.search(r'\(footprint "footprints:' + fpname + r'"(.*?)\n\t\)', t, re.S)
        m = re.search(r'np_thru_hole circle.*?\(drill ([\d.]+)\)', b.group(1), re.S) if b else None
        return float(m.group(1)) if m else None
    ex, ey = at(r"Bearing_[^\"]+")
    pads = []   # motor tab pads in panel coords (x, y, w, h); footprint at 0 deg rotation
    blk = re.search(r'\(footprint "footprints:Motor_1220_Tabs"(.*?)\n\t\)', t, re.S)
    if blk:
        for px, py, w, h in re.findall(r'\(pad "\d+" thru_hole \w+\s*\(at ([\d.\-]+) ([\d.\-]+)\)\s*\(size ([\d.]+) ([\d.]+)\)', blk.group(1)):
            pads.append((mx + float(px), my + float(py), float(w), float(h)))
    return dict(thickness=thick, motor_x=mx, motor_y=my, shaft_x=sx, shaft_y=sy,
                shaft_hole=drill(r"(?:Shaft_Hole_NPTH_[\d.]+mm|TubeRodClamp_Main_[^\"]+)"), motor_pads=pads,
                enc_x=ex, enc_y=ey, enc_hole=drill(r"Bearing_[^\"]+"))

def board_solid():
    """KiCad STEP, moved so its F (front, motor) face sits at Z = -Z_PCB_FRONT."""
    s = import_step(STEP)
    return Pos(0, 0, -Z_PCB_FRONT - s.bounding_box().max.Z) * s

if __name__ == "__main__":
    from sheet import Sheet
    f = kicad_facts(); b = board_solid(); bb = b.bounding_box()
    x0, x1, y0, y1 = bb.min.X, bb.max.X, -bb.max.Y, -bb.min.Y
    step_t = bb.size.Z
    zf = -Z_PCB_FRONT; zb = bb.min.Z
    mx, my = f["motor_x"], f["motor_y"]; hx, hy, hd = f["shaft_x"], f["shaft_y"], f["shaft_hole"]
    sh = Sheet(layout="panel", shape=b, gap=36, scale=1.3, label_pad=22)
    sh.hdim("front", x0, x1, -y1, -y1 - 9, f"{x1 - x0:.2f} board")
    sh.vdim("front", -y0, -y1, x0, x0 - 9, f"{y1 - y0:.2f} board")
    sh.hdim("front", x0, hx, -y0, -y0 + 6, f"{hx - x0:.2f} to shaft hole")
    sh.hdim("front", x0, mx, -y0, -y0 + 12, f"{mx - x0:.2f} to motor centre")
    sh.vdim("front", -y0, -hy, x1, x1 + 6, f"{hy - y0:.2f} (both)")
    sh.hdim("front", hx, mx, -hy, -hy - 9, f"{mx - hx:.1f} motor offset")
    sh.hdim("front", mx - 3, mx + 3, -my, -my - 4, "6.0 [A]")
    sh.hdim("front", hx - hd / 2, hx + hd / 2, -hy, -hy + 6, f"Ø{hd:.1f} NPTH [A]")
    ex, ey, ed = f["enc_x"], f["enc_y"], f["enc_hole"]
    if ex is not None:
        sh.vdim("front", -hy, -ey, x1, x1 + 14, f"{ey - hy:.2f} H2 (90° from the motor, on the centre line)")
        sh.hdim("front", ex - ed / 2, ex + ed / 2, -ey, -ey - 6, f"Ø{ed:.1f} NPTH H2 bearing [A]")
        sh.note("front", x0 + 2, -hy - 44, "H2 encoder bearing F682ZZ press fit from the FRONT through the base cradle floor [A]", 6.5)
    sh.note("front", x0 + 2, -hy - 34, "H1 on the dial axis [L]: TubeRodClamp_Main_M1.6, NPTH Ø1.8; F.Cu ring Ø3.4–Ø6.4 GND (tube soldered),", 6.5)
    sh.note("front", x0 + 2, -hy - 36.5, "    B.Cu ring Ø2.4–Ø4.4 VBUS_DATA under the M1.6 washer/nut [A]", 6.5)
    sh.note("front", x0 + 2, -hy - 46.5, "U2 Omron EE-SX1131 encoder sensor on B.Cu, 20.20 below H2 (36.20 below the dial axis), slot along x", 6.5)
    sh.note("front", x0 + 2, -hy - 39, "M1 Motor_1220_Tabs: 2 plated slots 0.7 × 1.6 [A], pitch 6.0", 6.5)
    sh.note("front", x0 + 2, -hy - 41.5, "v0.9: motor offset 11.0 = 12T pinion on the knob's 32T hub gear, m0.5 (was 14.0); H2 16.0 = 78T ring − 14T", 6.5)
    sh.hdim("side", -zf, -zb, -y1, -y1 - 4, f"{f['thickness']:.1f} board")
    sh.note("side", -zf - 1, -y1 - 11, f"front (F) face at {Z_PCB_FRONT:.1f} behind panel front [L]", 6.5, ha="center")
    title = "Knob main PCB — v0.9, 2026-10-31"
    sub = ["KiCad kicad/knob-main-pcb.kicad_pcb (STEP). v0.9: motor 11.0, H2 16.0, U2 EE-SX1131 on B; DRC 0.",
           f"Board x {x0:.2f}–{x1:.2f}, y {y0:.1f}–{y1:.1f} from panel top-left. [L] layout v5, [A] assumed.",
           f"Third-angle projection · mm · STEP body {step_t:.2f} (KiCad omits copper+mask)"]
    sh.dxf(os.path.join(HERE, "knob-main-pcb.dxf"), [title] + sub)
    sh.png(os.path.join(HERE, "knob-main-pcb-drawing.png"), title, sub)
    print(f, "bbox", x0, x1, y0, y1, "step_t", round(step_t, 3))
